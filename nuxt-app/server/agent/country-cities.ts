// Возвращает главный город, если name — известная страна, иначе null.
export function resolveSearchCity(name: string): string | null {
  return COUNTRY_CITIES[name.trim().toLowerCase()] ?? null
}

// Место — «страна», а не конкретный город (нужно уточнить город у пользователя).
export function isCountryName(place: { name: string; country?: string | null }): boolean {
  const name = place.name.trim().toLowerCase()
  if (CITY_STATES.has(name)) return false
  if (COUNTRY_CITIES[name]) return true
  const country = (place.country ?? '').trim().toLowerCase()
  return country !== '' && name === country
}